-- m4rket: esquema local reconstruido a partir de los modelos y peticiones existentes.
-- Datos exclusivamente de demostración; no es un respaldo de la universidad.
-- Importación no destructiva: no borra tablas ni actualiza registros existentes.
SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS m4rket_local CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE m4rket_local;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(255) NOT NULL,
 apellido VARCHAR(255) NOT NULL, email VARCHAR(255) NOT NULL, pwd VARCHAR(255) NOT NULL,
 genero ENUM('Hombre','Mujer') NOT NULL, rol ENUM('usuario','admin','superAdmin') DEFAULT 'usuario',
 UNIQUE KEY uq_usuarios_email (email)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS productos (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(255) NOT NULL,
 marca VARCHAR(255) NOT NULL, categoria VARCHAR(255) NOT NULL, stock INT NOT NULL,
 valor_energetico FLOAT NULL, grasas FLOAT NULL, grasas_saturadas FLOAT NULL,
 hidratos_carbono FLOAT NULL, azucares FLOAT NULL, fibra FLOAT NULL, proteina FLOAT NULL,
 sal FLOAT NULL, precio_kg FLOAT NULL, ingredientes VARCHAR(255) NULL,
 foto VARCHAR(255) NULL, precio FLOAT NOT NULL, KEY ix_productos_categoria (categoria)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ubicaciones (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, referencia VARCHAR(255) NOT NULL,
 posicion INT NOT NULL, UNIQUE KEY uq_ubicacion_posicion (referencia,posicion)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tipo_promocion (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(255) NOT NULL,
 descripcion VARCHAR(255) NOT NULL, modificador FLOAT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS promociones (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(255) NOT NULL,
 fecha_ini DATETIME NULL, fecha_fin DATETIME NULL, id_tipoPromo INT NULL,
 CONSTRAINT fk_promocion_tipo FOREIGN KEY (id_tipoPromo) REFERENCES tipo_promocion(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS en_ubicacion (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, idProd INT NOT NULL, idUbi INT NOT NULL,
 fecha_ini DATETIME NULL, fecha_fin DATETIME NULL, UNIQUE KEY uq_producto_ubicacion (idProd,idUbi),
 CONSTRAINT fk_ubicacion_producto FOREIGN KEY (idProd) REFERENCES productos(id) ON DELETE CASCADE,
 CONSTRAINT fk_ubicacion_ubicacion FOREIGN KEY (idUbi) REFERENCES ubicaciones(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS en_promocion (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, fecha DATETIME NULL, precio FLOAT NOT NULL,
 idPromo INT NOT NULL, idProd INT NOT NULL, UNIQUE KEY uq_producto_promocion (idProd,idPromo),
 CONSTRAINT fk_promocion_producto FOREIGN KEY (idProd) REFERENCES productos(id) ON DELETE CASCADE,
 CONSTRAINT fk_promocion_promocion FOREIGN KEY (idPromo) REFERENCES promociones(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS lista_compra (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, idUsu INT NOT NULL, idProd INT NOT NULL,
 fecha DATETIME NULL, cantidad INT NOT NULL, comprado TINYINT(1) DEFAULT 0,
 KEY ix_lista_usuario (idUsu),
 CONSTRAINT fk_lista_usuario FOREIGN KEY (idUsu) REFERENCES usuarios(id) ON DELETE CASCADE,
 CONSTRAINT fk_lista_producto FOREIGN KEY (idProd) REFERENCES productos(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS datos_contadores (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(255) NOT NULL,
 idProd INT NULL, fecha DATETIME NOT NULL, id_usuario VARCHAR(255) NULL, tiempo_uso INT NULL,
 KEY ix_contadores_nombre_fecha (nombre,fecha), KEY ix_contadores_producto (idProd),
 KEY ix_contadores_usuario (id_usuario)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS datos_tiempo (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(255) NOT NULL,
 fecha_ini DATETIME NOT NULL, fecha_fin DATETIME NOT NULL, idLista INT NULL, idUsu INT NULL,
 CONSTRAINT fk_tiempo_lista FOREIGN KEY (idLista) REFERENCES lista_compra(id) ON DELETE SET NULL,
 CONSTRAINT fk_tiempo_usuario FOREIGN KEY (idUsu) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB;

